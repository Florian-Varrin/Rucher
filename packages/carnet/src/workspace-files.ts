import {
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname } from 'node:path';
import { CarnetError } from './errors.ts';

export const GENERATED_MARKER = 'generated by rucher, do not edit';

function isGenerated(path: string): boolean {
  try {
    return readFileSync(path, 'utf8').includes(GENERATED_MARKER);
  } catch {
    return false;
  }
}

function refuse(path: string): never {
  throw new CarnetError(
    'WORKSPACE_FILE_CONFLICT',
    `${path} was not written by rucher: move its content to the group source, then remove it`,
  );
}

function entry(path: string): ReturnType<typeof lstatSync> | undefined {
  try {
    return lstatSync(path);
  } catch {
    return undefined;
  }
}

// Any link may be replaced: a renamed group leaves links to its old source.
export function ensureLink(path: string, target: string): boolean {
  const current = entry(path);
  if (current?.isSymbolicLink() && readlinkSync(path) === target) return false;
  if (current && !current.isSymbolicLink() && !isGenerated(path)) refuse(path);
  if (current) rmSync(path, { force: true });
  mkdirSync(dirname(path), { recursive: true });
  symlinkSync(target, path);
  return true;
}

export function writeGenerated(path: string, content: string): boolean {
  const current = entry(path);
  if (current?.isSymbolicLink()) rmSync(path, { force: true });
  else if (current) {
    const existing = readFileSync(path, 'utf8');
    if (existing === content) return false;
    if (!existing.includes(GENERATED_MARKER)) refuse(path);
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  return true;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function mergeSettings(
  base: Record<string, unknown>,
  extra: Record<string, unknown>,
): Record<string, unknown> {
  const merged: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(extra)) {
    const current = merged[key];
    if (Array.isArray(current) && Array.isArray(value)) {
      const seen = new Set(current.map((item) => JSON.stringify(item)));
      merged[key] = [...current, ...value.filter((item) => !seen.has(JSON.stringify(item)))];
    } else if (isObject(current) && isObject(value)) {
      merged[key] = mergeSettings(current, value);
    } else {
      merged[key] = value;
    }
  }
  return merged;
}
