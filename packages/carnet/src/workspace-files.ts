import { lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CarnetError } from './errors.ts';

export const GENERATED_MARKER = 'generated by rucher, do not edit';

function refuse(path: string): never {
  throw new CarnetError(
    'WORKSPACE_FILE_CONFLICT',
    `${path} was not written by rucher: move its content to the group source, then remove it`,
  );
}

function entry(path: string): ReturnType<typeof lstatSync> | undefined {
  try {
    return lstatSync(path);
  } catch {
    return undefined;
  }
}

// Claude Code strips HTML block comments from instruction files, so the marker costs no tokens.
export const MARKDOWN_MARKER = `<!-- ${GENERATED_MARKER} -->\n`;

export function markdownCopy(content: string): string {
  return `${MARKDOWN_MARKER}${content}`;
}

function isMarkdownCopy(path: string): boolean {
  const current = entry(path);
  if (!current?.isFile()) return false;
  return readFileSync(path, 'utf8').startsWith(MARKDOWN_MARKER);
}

// Copies whose source is gone, at the top level of the directory; hand-written files stay.
export function removeStaleCopies(directory: string, keep: ReadonlySet<string>): string[] {
  const removed: string[] = [];
  if (!entry(directory)) return removed;
  for (const name of readdirSync(directory)) {
    if (!name.endsWith('.md') || keep.has(name)) continue;
    const path = join(directory, name);
    if (!isMarkdownCopy(path)) continue;
    rmSync(path, { force: true });
    removed.push(name);
  }
  return removed;
}

export function writeGenerated(path: string, content: string): boolean {
  const current = entry(path);
  if (current?.isSymbolicLink()) rmSync(path, { force: true });
  else if (current) {
    const existing = readFileSync(path, 'utf8');
    if (existing === content) return false;
    if (!existing.includes(GENERATED_MARKER)) refuse(path);
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  return true;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function mergeSettings(
  base: Record<string, unknown>,
  extra: Record<string, unknown>,
): Record<string, unknown> {
  const merged: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(extra)) {
    const current = merged[key];
    if (Array.isArray(current) && Array.isArray(value)) {
      const seen = new Set(current.map((item) => JSON.stringify(item)));
      merged[key] = [...current, ...value.filter((item) => !seen.has(JSON.stringify(item)))];
    } else if (isObject(current) && isObject(value)) {
      merged[key] = mergeSettings(current, value);
    } else {
      merged[key] = value;
    }
  }
  return merged;
}
